import {
  basicCatalog,
  Catalog,
  createReactComponent,
  useA2UIState,
  type ReactComponentImplementation,
} from "@copilotkit/a2ui-renderer";
import { TableCellValue } from "./table-cell-value";
import { ResultTable, TablePaginationContext } from "./result-table";
import { isTableRecord } from "./table-data";
import { useContext } from "react";

const DefaultColumn = basicCatalog.components.get("Column")!.render;

function DingentTableRoot({
  context,
  buildChild,
}: Parameters<ReactComponentImplementation["render"]>[0]) {
  // Data-only pagination updates must redraw rows, not retain static Text cells.
  const { version } = useA2UIState();
  const paginationMode = useContext(TablePaginationContext);
  const data = context.dataContext.resolveDynamicValue<unknown>({ path: "/" });
  if (
    !isTableRecord(data) ||
    !Array.isArray(data.columns) ||
    !data.columns.every((column) => typeof column === "string") ||
    !Array.isArray(data.rows)
  ) {
    return <DefaultColumn context={context} buildChild={buildChild} />;
  }
  return (
    <ResultTable
      revision={version}
      data={{
        title: typeof data.title === "string" ? data.title : undefined,
        columns: data.columns,
        rows: data.rows,
      }}
      footer={
        paginationMode === "source" ? (
          <div className="flex flex-wrap items-center justify-end gap-2 py-3 [&_button]:h-9 [&_button]:rounded-md [&_button]:px-3 [&_button]:text-sm">
            <fieldset disabled={data.isFirstPage === true}>
              {buildChild("prevBtn")}
            </fieldset>
            <span className="text-xs text-muted-foreground">
              {typeof data.pageInfo === "string"
                ? data.pageInfo
                : buildChild("pageInfo")}
            </span>
            <fieldset disabled={data.isLastPage === true}>
              {buildChild("nextBtn")}
            </fieldset>
          </div>
        ) : undefined
      }
    />
  );
}

function createTableCatalog() {
  const column = basicCatalog.components.get("Column")!;
  const tableColumn = createReactComponent(
    column,
    ({ props, context, buildChild }) => {
      const children = props.children;
      // Custom third-party surfaces keep the SDK renderer and action handling.
      const isGeneratedTable =
        context.componentModel.id === "root" &&
        Array.isArray(children) &&
        children.includes("tableTitle") &&
        children.includes("tableHeader") &&
        children.includes("paginationRow") &&
        children.every(
          (id) =>
            ["tableTitle", "tableHeader", "paginationRow"].includes(id) ||
            /^row_\d+$/.test(id),
        );
      return isGeneratedTable ? (
        <DingentTableRoot context={context} buildChild={buildChild} />
      ) : (
        <DefaultColumn context={context} buildChild={buildChild} />
      );
    },
  );
  const text = basicCatalog.components.get("Text")!;
  const DefaultText = text.render;
  const cellText = createReactComponent(
    text,
    ({ props, context, buildChild }) => {
      // Only decorate cells generated by Dingent, not headings or button labels.
      if (/^row_\d+_cell_\d+$/.test(context.componentModel.id)) {
        return (
          <div className="m-2 min-w-0">
            <TableCellValue value={props.text} />
          </div>
        );
      }
      return <DefaultText context={context} buildChild={buildChild} />;
    },
  );
  return new Catalog<ReactComponentImplementation>(
    basicCatalog.id,
    [...basicCatalog.components.values()].map((component) =>
      component.name === "Text"
        ? cellText
        : component.name === "Column"
          ? tableColumn
          : component,
    ),
    [...basicCatalog.functions.values()],
    basicCatalog.themeSchema,
  );
}

export const tableCatalog = createTableCatalog();
